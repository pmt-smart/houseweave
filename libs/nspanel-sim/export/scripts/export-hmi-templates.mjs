// Extracts, from the Editor-made .HMI fixtures, one template per component
// type: the ordered attribute list (name, width, default value) and the
// default event slots, exactly as the Nextion Editor writes them for the
// F/Discovery series. Path D1 builds components from these
// templates instead of asking the Editor for fixtures.
//
//   node scripts/export-hmi-templates.mjs
//
// Writes hmi-templates/f-series.json (versioned, derived data) and
// src/hmiTemplates.generated.ts (imported by hmiWrite.ts). Requires
// `npm run build` and the manifest.hmi fixtures (`npm run fetch-fixtures`).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { readHmiDirectory, hmiLiveEntries, hmiBlob, readHmiComponents, KNOWN_LEI } from "../dist/index.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(readFileSync(join(root, "fixtures", "manifest.json"), "utf8"));
const names = Object.fromEntries(Object.entries(KNOWN_LEI).map(([k, v]) => [v, k]));

// Prefer the most "vanilla" instance of a type: the one with the fewest
// event script lines, then the smallest record. String attributes keep
// the width the Editor used for that instance; a builder resizes them.
// Templates come from the eseverson fixtures (Editor 1.67/1.68, iso-8859-1,
// the series we target); other projects (joBr99, Editor 1.65, UTF-8) only
// fill in types those fixtures lack.
const best = new Map();
const rank = (entry) => (entry.source === "eseverson" ? 0 : 1);
for (const entry of [...(manifest.hmi ?? [])].sort((a, b) => rank(a) - rank(b))) {
  const p = join(root, "fixtures", "cache", entry.name);
  if (!existsSync(p)) continue;
  const file = new Uint8Array(readFileSync(p));
  const live = hmiLiveEntries(readHmiDirectory(file));
  for (const [name, e] of live) {
    if (!/^\d+\.pa$/.test(name)) continue;
    for (const c of readHmiComponents(hmiBlob(file, e))) {
      const lines = c.events.reduce((n, ev) => n + ev.lines.length, 0);
      const cur = best.get(c.type);
      if (cur && cur.rank < rank(entry)) continue;
      if (!cur || lines < cur.lines || (lines === cur.lines && c.size < cur.size)) {
        best.set(c.type, { rank: rank(entry), lines, size: c.size, source: `${entry.name}/${name}#${c.row}`, component: c });
      }
    }
  }
}

const hex = (u8) => Array.from(u8).map((b) => b.toString(16).padStart(2, "0")).join("");
const templates = {};
for (const [type, { component: c, source }] of [...best].sort((a, b) => a[0] - b[0])) {
  templates[type] = {
    type,
    name: names[type] ?? `lei${type}`,
    header: c.header,
    source,
    attributes: c.attributes.map((a) => ({ name: a.name, width: a.width, defaultHex: hex(a.value) })),
    events: c.events.map((e) => e.event),
  };
}

const out = {
  $comment: "Per-type component templates as the Nextion Editor 1.67/1.68 writes them for the F/Discovery series (attribute order, widths, defaults; event slots). Extracted from the manifest.hmi fixtures by scripts/export-hmi-templates.mjs — do not edit by hand. String attributes (objname, txt, ...) are resized by the builder.",
  series: "F (Discovery), model NX4832F035_011",
  templates,
};
mkdirSync(join(root, "hmi-templates"), { recursive: true });
writeFileSync(join(root, "hmi-templates", "f-series.json"), JSON.stringify(out, null, 2) + "\n");
const ts = `// GENERATED by scripts/export-hmi-templates.mjs — do not edit.
// Per-type component templates as the Nextion Editor writes them for the
// F/Discovery series (attribute order, widths, default values, event slots).
export const HMI_TEMPLATES: Record<string, { type: number; name: string; header: string; source: string; attributes: { name: string; width: number; defaultHex: string }[]; events: string[] }> = ${JSON.stringify(templates, null, 2)};
`;
writeFileSync(join(root, "src", "hmiTemplates.generated.ts"), ts);
for (const t of Object.values(templates)) console.log(`${String(t.type).padStart(3)} ${t.name.padEnd(12)} ${t.attributes.length} attrs, events ${t.events.join(",") || "-"}  <- ${t.source}`);
console.log(`wrote hmi-templates/f-series.json and src/hmiTemplates.generated.ts (${Object.keys(templates).length} types)`);
